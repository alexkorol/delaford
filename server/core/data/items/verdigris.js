import { presetActions } from '#server/core/data/helpers/database.js';

const combatStats = (attack = {}, defense = {}) => ({
  attack: {
    stab: 0,
    slash: 0,
    crush: 0,
    range: 0,
    ...attack,
  },
  defense: {
    stab: 0,
    slash: 0,
    crush: 0,
    range: 0,
    ...defense,
  },
});

const wearable = ({
  id,
  name,
  examine,
  price,
  type,
  slot,
  size,
  artId,
  vesselForm,
  vesselMaterial,
  attack,
  defense,
  twoHanded = false,
}) => ({
  id,
  name,
  examine,
  price,
  type,
  slot,
  size,
  artId,
  vesselForm,
  vesselMaterial,
  stats: combatStats(attack, defense),
  graphics: {
    // Retained as a safe atlas fallback for old clients. The current client
    // resolves artId through src/core/inventory/item-art.js.
    tileset: type === 'weapon' ? 'weapons' : type === 'jewelry' ? 'jewelry' : 'armor',
    row: 0,
    column: 0,
    artId,
  },
  actions: presetActions(['wearable']),
  ...(twoHanded ? { twoHanded: true } : {}),
});

