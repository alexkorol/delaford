const EMPTY_STATS = Object.freeze({
  attack: Object.freeze({ stab: 0, slash: 0, crush: 0, range: 0 }),
  defense: Object.freeze({ stab: 0, slash: 0, crush: 0, range: 0 }),
});

const makeVesselItem = ({
  id,
  name,
  examine,
  formId,
  slot,
  type,
  graphics,
  twoHanded = false,
}) => ({
  id,
  name,
  examine,
  price: 0,
  type,
  slot,
  ...(type === 'weapon' ? { wearable: 'sword' } : {}),
  stats: EMPTY_STATS,
  graphics,
  actions: presetActions(['wearable']),
  disableAffixes: true,
  vesselforge: { formId },
  ...(twoHanded ? { twoHanded: true } : {}),
});

